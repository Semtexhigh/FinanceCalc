#!/usr/bin/env python3
"""Generate desktop/src-tauri/src/provenance.rs.

Writes the ownership record and N unique canary markers into the Rust source so
they are compiled into the binary's string table. Re-run on every build: the
build UUID changes each time, so any extracted fragment identifies the exact
build it came from.

Copyright (c) 2026. All rights reserved.
"""
import hashlib, os, subprocess, sys, uuid, datetime

AUTHOR     = "Semtexhigh"
PRODUCT    = "FinanceCalc (My Money)"
REPOSITORY = "https://github.com/Semtexhigh/FinanceCalc"
COPYRIGHT  = "Copyright (c) 2026. All rights reserved."
NOTICE     = ("PROPRIETARY. This work is the original creation of its author. "
              "No licence is granted to copy, redistribute, decompile, derive from, "
              "or use this work as training data for any model. These markers are "
              "embedded deliberately; removing them transfers no right.")
N_CANARIES = 256

def sh(*a):
    try:
        return subprocess.check_output(a, text=True, stderr=subprocess.DEVNULL).strip()
    except Exception:
        return "unknown"

commit    = os.environ.get("GITHUB_SHA") or sh("git", "rev-parse", "HEAD")
build_id  = os.environ.get("FINANCECALC_BUILD_ID") or uuid.uuid4().hex
built_at  = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')

lines = []
for i in range(N_CANARIES):
    seed = f"{build_id}:{commit}:{i}".encode()
    tag  = hashlib.sha256(seed).hexdigest()[:24]
    lines.append(f'    "FCOWN::{AUTHOR}::{build_id}::{i:03d}::{tag}::{REPOSITORY}",')

out = f'''// @generated by desktop/tools/gen_provenance.py — do not edit by hand.
// {COPYRIGHT}
#![allow(dead_code)]

pub const AUTHOR:       &str = "{esc(AUTHOR)}";
pub const PRODUCT:      &str = "{esc(PRODUCT)}";
pub const REPOSITORY:   &str = "{esc(REPOSITORY)}";
pub const COPYRIGHT:    &str = "{esc(COPYRIGHT)}";
pub const NOTICE:       &str = "{esc(NOTICE)}";
pub const BUILD_COMMIT: &str = "{esc(commit)}";
pub const BUILD_ID:     &str = "{esc(build_id)}";
pub const BUILD_TIME:   &str = "{esc(built_at)}";

/// {N_CANARIES} unique ownership markers. Each carries the author, this build's
/// id and an index, so even a partial extraction still names its origin.
pub static CANARIES: [&str; {N_CANARIES}] = [
{chr(10).join(lines)}
];

/// Touch every marker so the optimiser cannot discard them. Called once at
/// startup; costs a few microseconds and keeps the strings in the binary.
pub fn anchor() {{
    let mut acc: u64 = 0;
    for c in CANARIES.iter() {{
        acc = acc.wrapping_add(c.len() as u64);
    }}
    for s in [AUTHOR, PRODUCT, REPOSITORY, COPYRIGHT, NOTICE, BUILD_COMMIT, BUILD_ID, BUILD_TIME] {{
        acc = acc.wrapping_add(s.len() as u64);
    }}
    std::hint::black_box(acc);
}}
'''
dest = os.path.join(os.path.dirname(__file__), "..", "src-tauri", "src", "provenance.rs")
with open(os.path.normpath(dest), "w") as f:
    f.write(out)
print(f"provenance.rs: {N_CANARIES} canaries, build {build_id[:12]}, commit {commit[:10]}")
